"""Dialect protocols. Every backend must satisfy one of these contracts.

``BaseDialect`` is the contract for *company-managed* projects' shared
surface: detect/reflect, project CRUD, lead resolution, and the issue data
plane. ``CmpDialect`` extends it with the company-managed scheme surface
(custom fields, screens, screen schemes, issue-type screen schemes,
issue-type schemes, field configurations, issue types).

It does NOT apply to team-managed (TMP) projects: ``TmpDialect`` implements
none of it — no ``detect``, no project CRUD, a differently-shaped ``reflect``
(one project's ``snapshot` + its layouts), and its own internal-endpoint
write surface. That deviation is deliberate and documented in
``stint.dialects.jira.tmp`` — a team-managed backend satisfies nothing here,
contrary to what an earlier version of this docstring claimed (L29).

Concrete dialects (see ``stint.dialects.jira``) satisfy these structurally.
"""

from __future__ import annotations

from collections.abc import AsyncIterator
from typing import Any, ClassVar, Protocol

from stint.state.snapshot import Snapshot


class BaseDialect(Protocol):
    """The subset of the contract every backend style satisfies identically."""

    # Class-level constant: a backend identifies itself by `name` (e.g.
    # "jira_cloud"); nothing ever writes to it on an instance. ``ClassVar``
    # here lets concrete dialects declare ``name: ClassVar[str] = "..."``
    # in their class body without tripping ty's structural check against
    # the protocol (mutable ``name: str`` would require a writable
    # attribute, which a ClassVar isn't).
    name: ClassVar[str]

    # ── Detection / reflection ───────────────────────────────────────
    async def detect(self) -> bool:
        """Probe the backend and return True if this dialect matches it.

        Used for auto-detection when the user did not specify a dialect at
        engine creation. The implementation should make a single cheap call
        (e.g. `GET /serverInfo`) and inspect the response.
        """

    async def reflect(self) -> Snapshot:
        """Read the current admin state from the backend into a Snapshot.

        The Snapshot is dialect-agnostic. The planner consumes it without
        needing to know which backend produced it.
        """

    # ── Projects ─────────────────────────────────────────────────────
    async def resolve_lead(self, lead: str) -> str: ...
    async def create_project(
        self,
        *,
        key: str,
        name: str,
        project_type_key: str,
        lead: str,
        description: str = "",
        project_template_key: str | None = None,
    ) -> str: ...
    async def delete_project(self, *, project_id: str, project_key: str) -> None: ...
    async def add_project_role_actor(self, project_id: str, *, role_name: str, account_id: str) -> None: ...
    async def update_project(
        self, project_id: str, *, name: str | None = None, lead: str | None = None, description: str | None = None
    ) -> None: ...

    # ── Lockout-guard facts (project roles / permissions) ─────────────
    async def resolve_project_role_id(self, project_id: str, role_name: str) -> str: ...
    async def add_project_role_actors(
        self, project_id: str, *, role_id: str, users: list[str] | None = None, groups: list[str] | None = None
    ) -> None: ...
    async def remove_project_role_actor(
        self, project_id: str, *, role_id: str, user: str | None = None, group: str | None = None
    ) -> None: ...
    async def project_role_memberships(self, project_id: str, account_id: str) -> set[str]: ...
    async def my_account_id(self) -> str: ...
    async def user_groups(self, account_id: str) -> frozenset[str]: ...
    async def my_project_permissions(self, project_id: str, permissions: list[str]) -> dict[str, bool]: ...
    async def resolve_permission_holder(self, holder_type: str, holder_parameter: str) -> str: ...
    async def get_project_lead_account_id(self, project_id: str) -> str | None: ...

    # ── Issues (data plane) ──────────────────────────────────────────
    def search(self, *, jql: str, fields: list[str], page_size: int = 50) -> AsyncIterator[dict[str, Any]]: ...
    async def get_issue(self, key: str, *, fields: list[str]) -> dict: ...
    async def create_issue(self, body: dict[str, Any]) -> dict[str, Any]: ...
    async def update_issue(self, key: str, body: dict[str, Any]) -> None: ...
    async def delete_issue(self, key: str) -> None: ...

    # ── Workflow transitions (data plane) ────────────────────────────
    async def get_transitions(self, key: str) -> list[dict[str, Any]]: ...
    async def perform_transition(self, key: str, body: dict[str, Any]) -> None: ...

    # ── User resolution (data plane) ─────────────────────────────────
    async def resolve_user(self, value: str) -> str: ...

    # ── Comments (data plane) ────────────────────────────────────────
    def get_comments(self, key: str) -> AsyncIterator[dict[str, Any]]: ...
    async def add_comment(self, key: str, body: dict[str, Any]) -> dict[str, Any]: ...
    async def delete_comment(self, key: str, comment_id: str) -> None: ...

    # ── Changelog (data plane) ───────────────────────────────────────
    def get_changelog(self, key: str) -> AsyncIterator[dict[str, Any]]: ...

    # ── Attachments (data plane) ─────────────────────────────────────
    async def attach(self, key: str, *, data: bytes, filename: str) -> dict[str, Any]: ...
    async def get_attachments(self, key: str) -> list[dict[str, Any]]: ...
    async def download_attachment(self, attachment_id: str) -> bytes: ...
    async def delete_attachment(self, attachment_id: str) -> None: ...
    async def get_createmeta(self, project_key: str) -> dict[str, Any]: ...

    # ── Issue links (data plane) ─────────────────────────────────────
    async def get_issuelinks(self, key: str) -> list[dict[str, Any]]: ...
    async def create_issue_link(self, *, link_type: str, outward_key: str, inward_key: str) -> None: ...
    async def delete_issue_link(self, link_id: str) -> None: ...


class CmpDialect(BaseDialect, Protocol):
    """Adds the company-managed scheme surface on top of ``BaseDialect``."""

    # ── Custom fields ────────────────────────────────────────────────
    async def create_custom_field(
        self, *, name: str, description: str, type_id: str, searcher_key: str | None = None
    ) -> str: ...
    async def add_custom_field_option(self, field_id: str, value: str) -> str: ...
    async def delete_custom_field(self, field_id: str) -> None: ...
    async def update_custom_field(
        self, field_id: str, *, name: str | None = None, description: str | None = None, searcher_key: str | None = None
    ) -> None: ...
    async def delete_custom_field_option(self, field_id: str, option_id: str) -> None: ...

    # ── Screens ──────────────────────────────────────────────────────
    async def create_screen(self, *, name: str, description: str = "") -> str: ...
    async def delete_screen(self, screen_id: str) -> None: ...
    async def update_screen(
        self, screen_id: str, *, name: str | None = None, description: str | None = None
    ) -> None: ...
    async def add_screen_tab(self, screen_id: str, *, name: str) -> str: ...
    async def add_screen_tab_field(self, screen_id: str, tab_id: str, *, field_id: str) -> None: ...

    # ── Screen schemes ───────────────────────────────────────────────
    async def create_screen_scheme(self, *, name: str, description: str, screens: dict[str, str]) -> str: ...
    async def delete_screen_scheme(self, scheme_id: str) -> None: ...
    async def update_screen_scheme(
        self,
        scheme_id: str,
        *,
        name: str | None = None,
        description: str | None = None,
        screens: dict[str, str] | None = None,
    ) -> None: ...

    # ── Issue-type screen schemes ────────────────────────────────────
    async def create_issuetype_screen_scheme(
        self, *, name: str, description: str, mappings: list[dict[str, str]]
    ) -> str: ...
    async def delete_issuetype_screen_scheme(self, scheme_id: str) -> None: ...
    async def update_issuetype_screen_scheme(
        self, scheme_id: str, *, name: str | None = None, description: str | None = None
    ) -> None: ...
    async def set_issuetype_screen_scheme_mappings(self, scheme_id: str, *, mappings: list[dict[str, str]]) -> None: ...
    async def set_project_issuetype_screen_scheme(self, *, project_id: str, scheme_id: str) -> None: ...

    # ── Issue-type schemes ───────────────────────────────────────────
    async def create_issuetype_scheme(
        self, *, name: str, issuetype_ids: list[str], default_issuetype_id: str, description: str = ""
    ) -> str: ...
    async def update_issuetype_scheme(
        self,
        scheme_id: str,
        *,
        name: str | None = None,
        description: str | None = None,
        default_issuetype_id: str | None = None,
    ) -> None: ...
    async def set_issuetype_scheme_issuetypes(self, scheme_id: str, *, issuetype_ids: list[str]) -> None: ...
    async def delete_issuetype_scheme(self, scheme_id: str) -> None: ...
    async def set_project_issuetype_scheme(self, *, project_id: str, scheme_id: str) -> None: ...

    # ── Field configurations ─────────────────────────────────────────
    async def create_field_configuration(self, *, name: str, description: str = "") -> str: ...
    async def delete_field_configuration(self, fc_id: str) -> None: ...
    async def update_field_configuration(
        self, fc_id: str, *, name: str | None = None, description: str | None = None
    ) -> None: ...
    async def set_field_configuration_item(
        self, fc_id: str, *, field_id: str, required: bool = False, hidden: bool = False, description: str = ""
    ) -> None: ...
    async def create_field_configuration_scheme(self, *, name: str, description: str = "") -> str: ...
    async def delete_field_configuration_scheme(self, scheme_id: str) -> None: ...
    async def update_field_configuration_scheme(
        self, scheme_id: str, *, name: str | None = None, description: str | None = None
    ) -> None: ...
    async def set_field_configuration_scheme_mappings(
        self, scheme_id: str, *, mappings: list[dict[str, str]]
    ) -> None: ...
    async def set_project_field_configuration_scheme(self, *, project_id: str, scheme_id: str) -> None: ...

    # ── Issue security schemes ───────────────────────────────────────
    async def create_issue_security_scheme(
        self, *, name: str, description: str = "", levels: list[dict[str, Any]] | None = None
    ) -> str: ...
    async def update_issue_security_scheme(
        self, scheme_id: str, *, name: str | None = None, description: str | None = None
    ) -> None: ...
    async def delete_issue_security_scheme(self, scheme_id: str) -> None: ...
    async def associate_security_scheme_to_project(
        self,
        *,
        project_id: str,
        scheme_id: str,
        old_to_new_level_mappings: list[dict[str, str]] | None = None,
    ) -> dict[str, Any]: ...
    async def add_issue_security_levels(self, scheme_id: str, *, levels: list[dict[str, Any]]) -> None: ...
    async def add_issue_security_level_member(
        self, *, scheme_id: str, level_id: str, member_type: str, member_id_or_name: str
    ) -> None: ...
    async def remove_issue_security_level_member(
        self, *, scheme_id: str, level_id: str, member_id_or_name: str
    ) -> None: ...
    async def set_default_issue_security_levels(self, defaults: dict[str, str | None]) -> None: ...
    async def resolve_security_level_member(self, *, member_type: str, member_value: str) -> str: ...

    # ── Permission schemes ───────────────────────────────────────────
    async def create_permission_scheme(
        self, *, name: str, description: str = "", permissions: list[dict[str, Any]] | None = None
    ) -> str: ...
    async def update_permission_scheme(
        self, scheme_id: str, *, name: str | None = None, description: str | None = None
    ) -> None: ...
    async def delete_permission_scheme(self, scheme_id: str) -> None: ...
    async def get_permission_scheme(self, scheme_id: str) -> Any: ...
    async def find_permission_scheme_id_by_name(self, name: str) -> str | None: ...
    async def add_permission_grant(
        self, scheme_id: str, *, permission: str, holder_type: str, holder_parameter: str = ""
    ) -> str: ...
    async def remove_permission_grant(self, scheme_id: str, grant_id: str) -> None: ...
    async def assign_permission_scheme(self, *, project_id: str, scheme_id: str) -> None: ...
    async def get_project_permission_scheme_id(self, project_id: str) -> str | None: ...

    # ── Workflows / workflow schemes ─────────────────────────────────
    async def read_workflow_by_name(self, name: str) -> Any: ...
    async def create_workflows(
        self, *, statuses: list[dict[str, Any]], workflows: list[dict[str, Any]]
    ) -> dict[str, Any]: ...
    async def update_workflows(
        self, *, statuses: list[dict[str, Any]], workflows: list[dict[str, Any]]
    ) -> dict[str, Any]: ...
    async def delete_workflow(self, workflow_id: str) -> None: ...
    async def get_task(self, task_id: str) -> dict[str, Any]: ...
    async def resolve_status_ids(self, names: list[str]) -> dict[str, str | None]: ...
    async def global_project_role_ids(self) -> dict[str, str]: ...
    async def resolve_group_ids(self, names: list[str]) -> dict[str, str]: ...
    async def create_workflow_scheme(
        self,
        *,
        name: str,
        description: str = "",
        default_workflow: str = "",
        issue_type_mappings: dict[str, str] | None = None,
    ) -> str: ...
    async def update_workflow_scheme(
        self,
        scheme_id: str,
        *,
        name: str | None = None,
        description: str | None = None,
        default_workflow: str | None = None,
        issue_type_mappings: dict[str, str] | None = None,
    ) -> None: ...
    async def delete_workflow_scheme(self, scheme_id: str) -> None: ...
    async def find_workflow_scheme_id_by_name(self, name: str) -> str | None: ...
    async def get_workflow_scheme(self, scheme_id: str) -> Any: ...
    async def associate_workflow_scheme(self, *, project_id: str, scheme_id: str | None) -> None: ...
    async def switch_project_workflow_scheme(
        self,
        *,
        project_id: str,
        target_scheme_id: str,
        mappings_by_issue_type_override: list[dict[str, Any]] | None = None,
    ) -> dict[str, Any]: ...
    async def get_required_scheme_mappings(
        self,
        *,
        scheme_id: str,
        workflows_for_issue_types: list[dict[str, Any]],
        default_workflow_id: str | None = None,
    ) -> dict[str, Any]: ...

    # ── Issue types ──────────────────────────────────────────────────
    async def find_issuetype_id_by_name(self, name: str) -> str | None: ...
    async def create_issuetype(self, *, name: str, description: str = "", subtask: bool = False) -> str: ...
    async def delete_issuetype(self, issuetype_id: str) -> None: ...
    async def update_issuetype(
        self, issuetype_id: str, *, name: str | None = None, description: str | None = None
    ) -> None: ...
