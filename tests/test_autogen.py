def _docstring_first_line(source: str) -> str:
    """exec() the generated module source and return its docstring's first
    paragraph — proving the generated file is syntactically valid and the
    docstring value round-trips."""
    ns: dict[str, object] = {}
    exec(source, ns)
    return str(ns["__doc__"]).split("\n\n")[0]


