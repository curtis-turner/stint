def test_security_scheme_project_hint_warning():
    """A scheme whose ``project=`` hint names an undeclared project warns
    instead of silently emitting an unresolvable associate op."""
    from stint import SecurityLevel, SecurityScheme

    SecurityScheme(
        alias="orphan_hint",
        levels=[SecurityLevel(id="l1", name="L1")],
        project="NOSUCH",
    )
    desired = build_desired_snapshot()
