def test_emit_orders_schemes_before_projects_and_renders_ops():
    from stint.autogen.diff import CreateProject

    changes: list[Any] = [
        CreatePermissionScheme(
            alias="perm",
            name="Perm",
            description="",
            copy_from=None,
            grants=(("BROWSE_PROJECTS", "projectRole", "Viewers"),),
        ),
        CreateProject(alias="TRK", key="TRK", name="TRK", project_type_key="software", lead="x", description=""),
        AddProjectRoleActor(
            project_alias="TRK", role_name="Administrators", actor_type="user", actor_value="svc@example.com"
        ),
        SetProjectPermissionScheme(project_alias="TRK", scheme_alias="perm"),
        AddPermissionGrant(scheme_alias="perm", permission="ADD_COMMENTS", holder_type="group", holder_parameter="g"),
        RemovePermissionGrant(
            scheme_alias="perm", permission="BROWSE_PROJECTS", holder_type="group", holder_parameter="jira-users"
        ),
        RemoveProjectRoleActor(
            project_alias="TRK", role_name="Administrators", actor_type="user", actor_parameter="acct-1"
        ),
    ]
    ordered = sort_changes(changes)
    order = [type(c).__name__ for c in ordered]
    assert order.index("CreatePermissionScheme") < order.index("CreateProject")
    assert order.index("CreateProject") < order.index("AddProjectRoleActor")
    assert order.index("CreateProject") < order.index("SetProjectPermissionScheme")
    assert order.index("RemovePermissionGrant") > order.index("AddPermissionGrant")

    source = render_autogenerated("t", parents=None, revision="r0", changes=changes, allow_lockout=True)
    assert "op.create_permission_scheme(" in source
    assert "op.add_project_role_actor(" in source
    assert "op.set_project_permission_scheme(" in source
    assert "op.remove_permission_grant(" in source
    assert "allow_lockout=True" in source
    compile(source, "migration.py", "exec")  # the file must load


