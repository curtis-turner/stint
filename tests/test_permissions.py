def _dummy_issuetype(name: str = "Bug"):
    """A minimal stand-in for a registered IssueType (the metaclass only
    walks the list; validate()/desired tolerate unregistered aliases)."""
    return type(name, (), {"__alias__": name.lower()})


def test_project_roles_validation():
    it = [_dummy_issuetype()]
    with pytest.raises(ConfigurationError, match="invalid __roles__"):
        type("T", (Project,), {"__key__": "TRL", "__issuetypes__": it, "__roles__": "nope"})
    with pytest.raises(ConfigurationError, match="non-empty list"):
        type(
            "T",
            (Project,),
            {"__key__": "TRL", "__issuetypes__": it, "__roles__": {"Admins": []}},
        )
    with pytest.raises(ConfigurationError, match="invalid actor"):
        type(
            "T",
            (Project,),
            {"__key__": "TRL", "__issuetypes__": it, "__roles__": {"Admins": ["svc@example.com"]}},
        )
    with pytest.raises(ConfigurationError, match="conflict"):
        type(
            "T",
            (Project,),
            {
                "__key__": "TRL",
                "__issuetypes__": it,
                "__lead_role__": "Admins",
                "__roles__": {"Admins": [User("svc@example.com")]},
            },
        )


