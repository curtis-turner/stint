def test_permission_scheme_greenfield_creates_scheme_and_binds_existing_project():
    desired = _desired_scheme()
    state = _state_with_project()
    snapshot = _snapshot_with_project(
        permission_scheme_id="10000",
        permission_schemes={"10000": PermissionSchemeSnapshot(id="10000", name="Other")},
        project_roles={"Viewers": "10360"},
    )
    result = diff(desired=desired, snapshot=snapshot, state=state, allow_delete=False)
    creates = [c for c in result.changes if isinstance(c, CreatePermissionScheme)]
    assert len(creates) == 1
    assert creates[0].grants == (
        ("BROWSE_PROJECTS", "projectRole", "Viewers"),
        ("EDIT_ISSUES", "user", "svc@example.com"),
    )
    # Brownfield adoption: the existing project is bound to another scheme,
    # so the plan rebinds it (phase-ordered create → bind).
    binds = [c for c in result.changes if isinstance(c, SetProjectPermissionScheme)]
    assert [(c.project_alias, c.scheme_alias) for c in binds] == [("TRK", "perm")]


