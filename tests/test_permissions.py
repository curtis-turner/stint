def test_permission_scheme_grant_diff_adds_missing_and_gates_removals():
    desired = _desired_scheme()
    state = _state_with_project()
    state.permission_schemes["perm"] = PermissionSchemeMapping(id="20000")
    snapshot = _snapshot_with_project(
        permission_scheme_id="20000",
        permission_schemes={
            "20000": PermissionSchemeSnapshot(
                id="20000",
                name="Perm",
                grants=(
                    PermissionGrantSnapshot(
                        id="g1", permission="BROWSE_PROJECTS", holder_type="projectRole", holder_parameter="10360"
                    ),
                    PermissionGrantSnapshot(
                        id="g2", permission="BROWSE_PROJECTS", holder_type="group", holder_parameter="jira-users"
                    ),
                ),
            )
        },
        project_roles={"Viewers": "10360"},
    )
    result = diff(
        desired=desired,
        snapshot=snapshot,
        state=state,
        allow_delete=False,
        member_params={"svc@example.com": "acct-svc"},
    )
    adds = [c for c in result.changes if isinstance(c, AddPermissionGrant)]
    # Role grant already present (resolved by id); user grant missing.
    assert [(c.permission, c.holder_type, c.holder_parameter) for c in adds] == [
        ("EDIT_ISSUES", "user", "svc@example.com")
    ]
    # Exact policy (no copy_from): the undeclared group grant warns without
    # --allow-delete.
    assert any("Re-run with --allow-delete" in w for w in result.warnings)
    assert not any(isinstance(c, RemovePermissionGrant) for c in result.changes)

    allowed = diff(
        desired=desired,
        snapshot=snapshot,
        state=state,
        allow_delete=True,
        member_params={"svc@example.com": "acct-svc"},
    )
    removals = [c for c in allowed.changes if isinstance(c, RemovePermissionGrant)]
    assert [(c.permission, c.holder_type, c.holder_parameter) for c in removals] == [
        ("BROWSE_PROJECTS", "group", "jira-users")
    ]


