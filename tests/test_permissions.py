@pytest.mark.asyncio
@respx.mock
async def test_remove_permission_grant_guard_refuses_lockout():
    """Removing the last grant the account holds through a managed role is
    refused at op time; allow_lockout proceeds and records the removal."""
    mock = respx.mock
    _stub_guard_facts(mock, role_actors={"Administrators": [], "Viewers": []})
    # The bound scheme's grants: ADMINISTER_PROJECTS comes ONLY from role
    # 10360 (Administrators, which the account is NOT in after the role
    # stubs above show it empty) — but BROWSE comes from 10361 (Viewers,
    # also empty). Grant the account access via a user holder for BROWSE
    # and role for ADMINISTER; removing the user grant only threatens
    # BROWSE, which the Viewers role still grants (empty role membership →
    # actually refuses).
    mock.get(f"{CLOUD_ROOT}/permissionscheme/20000").mock(
        return_value=httpx.Response(
            200,
            json={
                "id": "20000",
                "name": "Perm",
                "permissions": [
                    {
                        "id": "g1",
                        "permission": "BROWSE_PROJECTS",
                        "holder": {"type": "projectRole", "parameter": "10361"},
                    },
                    {"id": "g2", "permission": "BROWSE_PROJECTS", "holder": {"type": "user", "parameter": "acct-svc"}},
                    {
                        "id": "g3",
                        "permission": "ADMINISTER_PROJECTS",
                        "holder": {"type": "projectRole", "parameter": "10360"},
                    },
                ],
            },
        )
    )
    mock.delete(url__regex=r"/permissionscheme/20000/permission/g2").mock(return_value=httpx.Response(204))
    engine = _engine()
    state = _state_with_project()
    state.permission_schemes["perm"] = PermissionSchemeMapping(id="20000")
    from stint.exceptions import StintError

    async with engine:
        with pytest.raises(StintError, match="allow_lockout"):
            await _run_in_ctx(
                engine,
                state,
                lambda: op.remove_permission_grant(
                    scheme_alias="perm",
                    permission="BROWSE_PROJECTS",
                    holder_type="user",
                    holder_parameter="acct-svc",
                    required_permissions=["BROWSE_PROJECTS"],
                ),
            )
        assert not any(c.request.method == "DELETE" and "/permission/g" in str(c.request.url) for c in mock.calls)

        # Escape hatch: the removal proceeds and state drops the grant.
        await _run_in_ctx(
            engine,
            state,
            lambda: op.remove_permission_grant(
                scheme_alias="perm",
                permission="BROWSE_PROJECTS",
                holder_type="user",
                holder_parameter="acct-svc",
                allow_lockout=True,
            ),
        )
    assert not any(
        g["permission"] == "BROWSE_PROJECTS" and g["type"] == "user" for g in state.permission_schemes["perm"].grants
    )


