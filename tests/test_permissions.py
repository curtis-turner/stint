def test_validate_rejects_unregistered_permission_scheme_reference():
    # A declared-but-unbound scheme is fine; referencing a scheme that was
    # never constructed is the error validate() must catch.
    import types

    module = types.ModuleType("schemas")
    module.__dict__["project_cls"] = type(
        "Tracker",
        (Project,),
        {
            "__key__": "VAL",
            "__issuetypes__": [_dummy_issuetype()],
            "__permission_scheme__": types.SimpleNamespace(alias="ghost"),
        },
    )
    registry.register_project(module.project_cls)
    try:
        problems = validate()
        assert any("PermissionScheme" in p and "not registered" in p for p in problems)
    finally:
        registry.projects.pop("VAL", None)


