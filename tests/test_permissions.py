def _snapshot_with_project(
    *,
    key: str = "TRK",
    project_id: str = "10010",
    roles: dict[str, tuple[RoleActorSnapshot, ...]] | None = None,
    permission_scheme_id: str | None = None,
    permission_schemes: dict[str, PermissionSchemeSnapshot] | None = None,
    project_roles: dict[str, str] | None = None,
) -> Snapshot:
    from stint.state.snapshot import ProjectSnapshot, ServerInfoSnapshot

    snap = Snapshot(server_info=ServerInfoSnapshot(deployment_type="Cloud", version="1", base_url=BASE))
    snap.projects[key] = ProjectSnapshot(
        id=project_id,
        key=key,
        name=key,
        roles=roles or {},
        permission_scheme_id=permission_scheme_id,
    )
    snap.permission_schemes = permission_schemes or {}
    snap.project_roles = project_roles or {}
    return snap


